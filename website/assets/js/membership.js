function translateMembershipPage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (membershipTranslations[lang] && membershipTranslations[lang][key]) {
            element.innerHTML = membershipTranslations[lang][key];
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    // 1. Инициализация языка
    const savedLang = localStorage.getItem('preferred_lang') || 'ru';
    translateMembershipPage(savedLang);

    // 2. Обработка переключения языка
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            
            const lang = btn.getAttribute('data-lang') || 'ru';
            localStorage.setItem('preferred_lang', lang);
            translateMembershipPage(lang);
        });
    });

    // 3. Плавный скролл к секции подачи заявки
    document.querySelectorAll('a[href^="#apply"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'center'
                });
            }
        });
    });
});